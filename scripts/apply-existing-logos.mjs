// Puts the logos found by scripts/find-logos-existing.mjs (data/logos-existing.json) onto the existing firms:
//  1. each firm's hand-built page (firms/<slug>.html) swaps its initials badge (or a logo hot-linked from the firm's own site) for the saved picture;
//  2. db/logo-updates.sql sets type/src on the firm's database record, so search, the map, city pages and "Browse other lawyers"
//     show it too. It only touches records still showing initials, so a logo an admin or owner uploaded is never replaced.
//   node scripts/apply-existing-logos.mjs          writes the pages and db/logo-updates.sql
//   node scripts/apply-existing-logos.mjs --check  fails if either is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const CHECK = process.argv.includes('--check');
const map = JSON.parse(readFileSync(new URL('data/logos-existing.json', root), 'utf8'));
const firms = Object.fromEntries(JSON.parse(readFileSync(new URL('firms_data.json', root), 'utf8')).map((f) => [f.slug, f]));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

const sql = ['-- Generated by scripts/apply-existing-logos.mjs from data/logos-existing.json. Do not edit by hand.'];
let changed = 0, stale = 0;
for (const [slug, { src }] of Object.entries(map).sort()) {
  const f = firms[slug];
  if (!f || f.type === 'logo' || !existsSync(new URL(src, root))) { console.error('skipped', slug); continue; }
  const page = new URL(`firms/${slug}.html`, root);
  if (existsSync(page)) {
    const html = readFileSync(page, 'utf8');
    // The badge is either just the initials, or the initials with the firm's logo hot-linked from its own site on top: both become one local picture.
    const badge = /<span class="li-logo">(?:(?!<\/span>)[\s\S])*<\/span>/;
    const want = `<span class="li-logo"><img src="../${src}" alt="${esc(f.name)} logo" width="96" height="96"></span>`;
    if (html.includes(want)) { /* already applied */ } else if (badge.test(html)) {
      changed++;
      if (CHECK) stale++; else writeFileSync(page, html.replace(badge, want));
    } else if (!html.includes(`../${src}`)) console.error('no logo badge found in', slug);
  }
  sql.push(`UPDATE firms SET data = json_set(data, '$.type', 'logo', '$.src', ${q(src)}), updated_at = datetime('now') WHERE slug = ${q(slug)} AND json_extract(data, '$.type') = 'mono';`);
}
const out = sql.join('\n') + '\n';
const target = new URL('db/logo-updates.sql', root);
if (CHECK) {
  if (stale || !existsSync(target) || readFileSync(target, 'utf8') !== out) { console.error('logos are not applied: run node scripts/apply-existing-logos.mjs'); process.exit(1); }
  console.log(`existing-firm logos applied: ${sql.length - 1} firms`);
} else { writeFileSync(target, out); console.log(`${changed} pages updated, ${sql.length - 1} database updates`); }
