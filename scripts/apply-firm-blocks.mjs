// Puts the hand-written "From the Firm" / "Related reading" blocks (data/firm-blocks.json, read from the hand-built pages by
// scripts/extract-firm-blocks.mjs) into the database records, so a firm's database page shows what its hand-built page shows.
// db/block-updates.sql fills a record only while it has no block yet.
// The hand-copied "From the Firm" articles were taken off for good (the live blog cards replace them): any "From the Firm" block already in a record is removed.
//   node scripts/apply-firm-blocks.mjs          writes db/block-updates.sql
//   node scripts/apply-firm-blocks.mjs --check  fails if it is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const blocks = JSON.parse(readFileSync('data/firm-blocks.json', 'utf8'));
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const sql = ['-- Generated by scripts/apply-firm-blocks.mjs from data/firm-blocks.json. Do not edit by hand.',
  "UPDATE firms SET data = json_remove(data, '$.block'), updated_at = datetime('now') WHERE json_extract(data, '$.block.heading') = 'From the Firm';"];
for (const [slug, b] of Object.entries(blocks).sort()) {
  sql.push(`UPDATE firms SET data = json_set(data, '$.block', json(${q(JSON.stringify(b))})), updated_at = datetime('now') WHERE slug = ${q(slug)} AND json_extract(data, '$.block') IS NULL;`);
}
const out = sql.join('\n') + '\n';
const target = 'db/block-updates.sql';
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) { console.error('block updates are out of date: run node scripts/apply-firm-blocks.mjs'); process.exit(1); }
  console.log(`firm blocks up to date: ${sql.length - 2} firms`);
} else { writeFileSync(target, out); console.log(`${sql.length - 2} block updates`); }
