// Puts the online booking links listed in data/firm-booking.json ({ slug: { url, kind: 'calendar' | 'page', tool?, checked } }) on the firm records,
// so a firm's page can show an active "Book a call" button (src/render/booking.js). The links were found on each firm's own website
// (a scan of every listed firm's home page and contact page: a calendar such as Calendly, Clio or Microsoft Bookings, or a page or form the firm itself
// labels "Book" or "Schedule"), each one was opened to check that it loads, and links that only point to the home page or to another firm's site were left out.
//  - batch firms (data/firms-batch-N.json): a `bookingUrl` on the record;
//  - db/booking-updates.sql: the same for every firm already in the database (hand-built firms too), only where no link is set yet,
//    so a link an owner or an admin typed in later is never replaced.
//   node scripts/apply-firm-booking.mjs          writes everything
//   node scripts/apply-firm-booking.mjs --check  fails if anything is out of date
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { cleanBookingUrl } from '../src/lib/booking.js';

const CHECK = process.argv.includes('--check');
const booking = JSON.parse(readFileSync('data/firm-booking.json', 'utf8'));
let stale = 0;
const write = (file, text) => {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { if (CHECK) { stale++; console.error('out of date:', file); } else writeFileSync(file, text); }
};
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

const batches = {};
const batchOf = new Map();
for (const file of readdirSync('data').filter((f) => /^firms-batch-\d+\.json$/.test(f)).sort()) {
  batches[file] = JSON.parse(readFileSync(`data/${file}`, 'utf8'));
  for (const f of batches[file]) { batchOf.set(f.slug, f); delete f.bookingUrl; }
}
const known = new Set([...batchOf.keys(), ...JSON.parse(readFileSync('firms_data.json', 'utf8')).map((f) => f.slug)]);

const sql = ['-- Generated by scripts/apply-firm-booking.mjs from data/firm-booking.json. Do not edit by hand.'];
for (const [slug, b] of Object.entries(booking).sort()) {
  if (!known.has(slug)) throw new Error(`${slug}: not a firm`);
  if (!['calendar', 'page'].includes(b.kind)) throw new Error(`${slug}: kind must be calendar or page`);
  if (cleanBookingUrl(b.url) !== b.url) throw new Error(`${slug}: ${b.url} is not a clean booking link (run it through cleanBookingUrl in src/lib/booking.js)`);
  sql.push(`UPDATE firms SET data = json_set(data, '$.bookingUrl', ${q(b.url)}), updated_at = datetime('now') WHERE slug = ${q(slug)} AND json_extract(data, '$.bookingUrl') IS NULL;`);
  if (batchOf.has(slug)) batchOf.get(slug).bookingUrl = b.url;
}
for (const [file, list] of Object.entries(batches)) write(`data/${file}`, JSON.stringify(list, null, 1) + '\n');
write('db/booking-updates.sql', sql.join('\n') + '\n');

if (CHECK) {
  if (stale) process.exit(1);
  console.log(`firm booking links up to date: ${Object.keys(booking).length} firms`);
} else console.log(`firm booking links applied: ${Object.keys(booking).length} firms`);
