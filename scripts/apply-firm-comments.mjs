// Chooses the comments shown under "What clients say" on a firm profile and writes them as database updates.
//   python3 -I scripts/find-firm-comments.py <out-dir> --export=data/firm-comments.json     (reads the firms' own websites; candidates, up to 6 per firm)
//   node scripts/apply-firm-comments.mjs          writes db/comments-updates.sql
//   node scripts/apply-firm-comments.mjs --check  fails if the file is out of date
// Every candidate goes through cleanComments (src/lib/comments.js): the site's own text rules, no links or sensitive stories, a source on the firm's own
// website, at most three per firm. db/comments-updates.sql sets `comments` in the firm's record (a firm whose record says commentsOff stays untouched).
// It is applied with the other db/*-updates.sql files (npm run db:updates:local / db:updates:remote). Nothing here changes the live site by itself.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { cleanComments } from '../src/lib/comments.js';

const CHECK = process.argv.includes('--check');
const cand = existsSync('data/firm-comments.json') ? JSON.parse(readFileSync('data/firm-comments.json', 'utf8')) : {};

const sites = new Map(JSON.parse(readFileSync('firms_data.json', 'utf8')).map((f) => [f.slug, f.website]));
for (const file of readdirSync('data').filter((f) => /^firms-batch-\d+\.json$/.test(f)).sort()) {
  for (const f of JSON.parse(readFileSync(`data/${file}`, 'utf8'))) if (!sites.has(f.slug)) sites.set(f.slug, f.website);
}

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const sql = ['-- Generated by scripts/apply-firm-comments.mjs from data/firm-comments.json. Do not edit by hand.'];
const counts = { 3: 0, 2: 0, 1: 0, 0: 0 };
let dropped = 0;
for (const slug of Object.keys(cand).sort()) {
  if (!sites.has(slug)) throw new Error(`comments for unknown firm: ${slug}`);
  const list = cleanComments(cand[slug].comments, { website: sites.get(slug) });
  const n = list ? list.length : 0;
  counts[n]++;
  dropped += cand[slug].comments.length - n;
  if (!list) continue;
  sql.push(`UPDATE firms SET data = json_set(data, '$.comments', json(${q(JSON.stringify(list))})), updated_at = datetime('now') WHERE slug = ${q(slug)} AND COALESCE(json_extract(data, '$.commentsOff'), 0) = 0;`);
}
const text = sql.join('\n') + '\n';
const file = 'db/comments-updates.sql';
const stale = !existsSync(file) || readFileSync(file, 'utf8') !== text;
if (CHECK) {
  if (stale) { console.error('out of date:', file); process.exit(1); }
  console.log(`firm comments up to date: ${counts[1] + counts[2] + counts[3]} firms`);
} else {
  if (stale) writeFileSync(file, text);
  console.log(`firm comments: ${counts[3]} firms with 3, ${counts[2]} with 2, ${counts[1]} with 1, ${counts[0]} left with none after the site's rules; ${dropped} candidates dropped`);
}
