// Puts the facts in data/firm-details.json ({ slug: { founded, languages, lawyers, areas, serving } }, built by scripts/extract-firm-details.mjs)
// on the firm profiles:
//  - firms from data/firms-batch-N.json: a `details` field on the batch record, which the database page shows as "At a glance";
//  - db/details-updates.sql: the same for batch firms already in the database, only where no details are stored yet
//    (facts typed in later by an owner or an admin are never replaced).
//   node scripts/apply-firm-details.mjs          writes everything
//   node scripts/apply-firm-details.mjs --check  fails if anything is out of date
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { cleanDetails } from '../src/lib/details.js';

const CHECK = process.argv.includes('--check');
const details = existsSync('data/firm-details.json') ? JSON.parse(readFileSync('data/firm-details.json', 'utf8')) : {};
let stale = 0;
const write = (file, text) => {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { if (CHECK) { stale++; console.error('out of date:', file); } else writeFileSync(file, text); }
};
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

const sql = ['-- Generated by scripts/apply-firm-details.mjs from data/firm-details.json. Do not edit by hand.'];
const known = new Set();
for (const file of readdirSync('data').filter((f) => /^firms-batch-\d+\.json$/.test(f)).sort()) {
  const batch = JSON.parse(readFileSync(`data/${file}`, 'utf8'));
  for (const f of batch) {
    const d = details[f.slug];
    if (!d) { delete f.details; continue; }
    const clean = cleanDetails(d);
    if (!clean || JSON.stringify(clean) !== JSON.stringify(d)) throw new Error(`${f.slug}: details are not clean (run the verify step again)`);
    known.add(f.slug);
    f.details = clean;
    sql.push(`UPDATE firms SET data = json_set(data, '$.details', json(${q(JSON.stringify(clean))})), updated_at = datetime('now') WHERE slug = ${q(f.slug)} AND json_extract(data, '$.details') IS NULL;`);
  }
  write(`data/${file}`, JSON.stringify(batch, null, 1) + '\n');
}
const missing = Object.keys(details).filter((s) => !known.has(s));
if (missing.length) throw new Error('details for unknown firms: ' + missing.slice(0, 5).join(', '));
write('db/details-updates.sql', sql.join('\n') + '\n');

if (CHECK) {
  if (stale) process.exit(1);
  console.log(`firm details up to date: ${Object.keys(details).length} firms`);
} else console.log(`firm details applied to ${Object.keys(details).length} firms`);
