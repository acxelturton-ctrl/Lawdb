// Writes the lawyers of each firm as database updates (db/lawyers-updates.sql) from data/firm-lawyers.json (scripts/prepare-firm-lawyers.py).
//   node scripts/apply-firm-lawyers.mjs          writes db/lawyers-updates.sql
//   node scripts/apply-firm-lawyers.mjs --check  fails if the file is out of date
// Every list goes through cleanLawyers (src/lib/lawyers.js): a name that is not a person's name, a bad address or odd text is dropped, and a firm left with fewer
// than two lawyers gets none. The update sets `lawyers` in the firm's record; a firm whose record says lawyersOff, or whose owner has edited the list
// (lawyersLocked), stays untouched. It is applied with the other db/*-updates.sql files (npm run db:updates:local / db:updates:remote). Pictures are kept as
// addresses with photoConfirmed false: a page shows none of them until one is confirmed.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { cleanLawyers, lawyerHasPage, MIN_FIRM_LAWYERS } from '../src/lib/lawyers.js';

const CHECK = process.argv.includes('--check');
const data = existsSync('data/firm-lawyers.json') ? JSON.parse(readFileSync('data/firm-lawyers.json', 'utf8')) : {};
const slugs = new Set(JSON.parse(readFileSync('firms_data.json', 'utf8')).map((f) => f.slug));
for (const file of readdirSync('data').filter((f) => /^firms-batch-\d+\.json$/.test(f))) for (const f of JSON.parse(readFileSync(`data/${file}`, 'utf8'))) slugs.add(f.slug);

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const sql = ['-- Generated by scripts/apply-firm-lawyers.mjs from data/firm-lawyers.json. Do not edit by hand.'];
let firms = 0, lawyers = 0, pages = 0;
for (const slug of Object.keys(data).sort()) {
  if (!slugs.has(slug)) throw new Error(`lawyers for unknown firm: ${slug}`);
  // store the cleaned form, with the picture address kept but not yet confirmed
  const keep = cleanLawyers(data[slug].map((l) => ({ ...l, photoConfirmed: true }))).map((l) => (l.photo ? { ...l, photoConfirmed: false } : l));
  if (keep.length < MIN_FIRM_LAWYERS) continue;
  firms++; lawyers += keep.length; pages += keep.filter(lawyerHasPage).length;
  sql.push(`UPDATE firms SET data = json_set(data, '$.lawyers', json(${q(JSON.stringify(keep))})), updated_at = datetime('now') WHERE slug = ${q(slug)} AND COALESCE(json_extract(data, '$.lawyersOff'), 0) = 0 AND json_extract(data, '$.lawyersLocked') IS NULL;`);
}
const text = sql.join('\n') + '\n';
const file = 'db/lawyers-updates.sql';
const stale = !existsSync(file) || readFileSync(file, 'utf8') !== text;
if (CHECK) {
  if (stale) { console.error('out of date:', file); process.exit(1); }
  console.log(`firm lawyers up to date: ${lawyers} lawyers at ${firms} firms (${pages} with a page of their own)`);
} else {
  if (stale) writeFileSync(file, text);
  console.log(`firm lawyers: ${lawyers} lawyers at ${firms} firms, ${pages} with a page of their own`);
}
