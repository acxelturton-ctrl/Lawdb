// Puts the pictures listed in data/firm-photos.json ({ slug: { kind: 'cover' | 'bio', src, from } }) on the firm profiles.
// The pictures are each firm's own share picture from its website (scripts/find-firm-photos.mjs) that a person looked at and chose;
// the files are in images/hero/ (covers) and images/bio/ (bio pictures, shown under the description).
//  - hand-built pages (firms/<slug>.html): a cover replaces the plain city banner; a bio picture is added under the description
//    (not when the page already has a firm photo);
//  - batch firms (data/firms-batch-N.json): `heroImage` / `bioImage` on the record, which the database page renders;
//  - db/photo-updates.sql: the same for batch firms already in the database, only where no picture is set yet.
//   node scripts/apply-firm-photos.mjs          writes everything
//   node scripts/apply-firm-photos.mjs --check  fails if anything is out of date
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';

const CHECK = process.argv.includes('--check');
const photos = JSON.parse(readFileSync('data/firm-photos.json', 'utf8'));
let stale = 0;
const write = (file, text) => {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { if (CHECK) { stale++; console.error('out of date:', file); } else writeFileSync(file, text); }
};
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#x27;');
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

const batchOf = new Map();
const batches = {};
for (const file of readdirSync('data').filter((f) => /^firms-batch-\d+\.json$/.test(f)).sort()) {
  batches[file] = JSON.parse(readFileSync(`data/${file}`, 'utf8'));
  for (const f of batches[file]) batchOf.set(f.slug, f);
}

const sql = ['-- Generated by scripts/apply-firm-photos.mjs from data/firm-photos.json. Do not edit by hand.'];
for (const [slug, p] of Object.entries(photos).sort()) {
  if (!existsSync(p.src)) throw new Error(`${slug}: ${p.src} is missing`);
  const key = p.kind === 'cover' ? 'heroImage' : 'bioImage';
  if (batchOf.has(slug)) {
    batchOf.get(slug)[key] = p.src;
    sql.push(`UPDATE firms SET data = json_set(data, '$.${key}', ${q(p.src)}), updated_at = datetime('now') WHERE slug = ${q(slug)} AND json_extract(data, '$.${key}') IS NULL;`);
    continue;
  }
  const path = `firms/${slug}.html`;
  if (!existsSync(path)) throw new Error(`${slug}: no firm`);
  let html = readFileSync(path, 'utf8');
  const name = (html.match(/<h1 class="li-name">([^<]*)/) || [, slug])[1].trim();
  if (p.kind === 'cover') {
    const gen = html.match(/<div class="li-cover gen">[\s\S]*?<\/span><\/div>/);
    if (gen) html = html.replace(gen[0], () => `<div class="li-cover"><img src="../${p.src}" alt="${name}" loading="eager"></div>`);
  } else if (!html.includes('class="firm-photo"') && !html.includes(`../${p.src}`)) {
    html = html.replace(/(<div class="article">[\s\S]*?<\/div>)/, (m) => `${m}\n    <figure style="margin:0 0 18px;"><img src="../${p.src}" alt="${name}" loading="lazy" style="display:block;width:100%;max-width:520px;height:auto;border-radius:12px;"></figure>`);
  }
  write(path, html);
}
for (const [file, list] of Object.entries(batches)) write(`data/${file}`, JSON.stringify(list, null, 1) + '\n');
write('db/photo-updates.sql', sql.join('\n') + '\n');

if (CHECK) {
  if (stale) process.exit(1);
  console.log(`firm photos up to date: ${Object.keys(photos).length} pictures`);
} else console.log(`firm photos applied: ${Object.keys(photos).length} pictures`);
