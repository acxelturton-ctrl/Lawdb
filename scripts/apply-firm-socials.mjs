// Puts the social profile links listed in data/firm-socials.json ({ slug: { facebook, instagram, linkedin, x, youtube } }) on the firm records:
// the links come from each firm's own website (scripts/find-firm-socials.mjs) and a person looked at the result before it was listed here.
//  - batch firms (data/firms-batch-N.json): a `social` object on the record;
//  - db/social-updates.sql: the same for every firm already in the database (hand-built firms too), only where no social links are set yet.
// The story card (src/render/story-page.js) shows them as round icons in its "About the firm" box.
//   node scripts/apply-firm-socials.mjs          writes everything
//   node scripts/apply-firm-socials.mjs --check  fails if anything is out of date
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { cleanSocial } from '../src/lib/social.js';

const CHECK = process.argv.includes('--check');
const socials = JSON.parse(readFileSync('data/firm-socials.json', 'utf8'));
let stale = 0;
const write = (file, text) => {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { if (CHECK) { stale++; console.error('out of date:', file); } else writeFileSync(file, text); }
};
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

const batches = {};
const batchOf = new Map();
for (const file of readdirSync('data').filter((f) => /^firms-batch-\d+\.json$/.test(f)).sort()) {
  batches[file] = JSON.parse(readFileSync(`data/${file}`, 'utf8'));
  for (const f of batches[file]) batchOf.set(f.slug, f);
}
const known = new Set([...batchOf.keys(), ...JSON.parse(readFileSync('firms_data.json', 'utf8')).map((f) => f.slug)]);

const sql = ['-- Generated by scripts/apply-firm-socials.mjs from data/firm-socials.json. Do not edit by hand.'];
for (const [slug, raw] of Object.entries(socials).sort()) {
  if (!known.has(slug)) throw new Error(`${slug}: not a firm`);
  const clean = cleanSocial(raw);
  if (!Object.keys(clean).length || JSON.stringify(clean) !== JSON.stringify(Object.fromEntries(Object.keys(clean).map((k) => [k, raw[k]])))) {
    throw new Error(`${slug}: ${JSON.stringify(raw)} is not a clean list of social profile addresses (run it through cleanSocial in src/lib/social.js)`);
  }
  sql.push(`UPDATE firms SET data = json_set(data, '$.social', json(${q(JSON.stringify(clean))})), updated_at = datetime('now') WHERE slug = ${q(slug)} AND json_extract(data, '$.social') IS NULL;`);
  if (batchOf.has(slug)) batchOf.get(slug).social = clean;
}
for (const [file, list] of Object.entries(batches)) write(`data/${file}`, JSON.stringify(list, null, 1) + '\n');
write('db/social-updates.sql', sql.join('\n') + '\n');

if (CHECK) {
  if (stale) process.exit(1);
  console.log(`firm socials up to date: ${Object.keys(socials).length} firms`);
} else console.log(`firm socials applied: ${Object.keys(socials).length} firms`);
