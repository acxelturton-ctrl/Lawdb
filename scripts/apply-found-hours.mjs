// Puts the opening hours the firms publish on their own websites (data/hours-found.json, from scripts/find-hours.mjs) where they show:
//  - firms from a batch file (data/firms-batch-N.json): written into the batch record, so db/extra-firms.sql carries them;
//  - the original hand-built firms: added to firms_hours.json, to the firm's page (an hours card before the "Before you call" guide),
//    and to db/hours-updates.sql, which fills the database only where a firm has no hours yet (hours typed in the admin area are never replaced).
//   node scripts/apply-found-hours.mjs          writes everything
//   node scripts/apply-found-hours.mjs --check  fails if anything is out of date
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { hoursCard } from '../src/render/firm-page.js';

const CHECK = process.argv.includes('--check');
const found = JSON.parse(readFileSync('data/hours-found.json', 'utf8'));
const firms = Object.fromEntries(JSON.parse(readFileSync('firms_data.json', 'utf8')).map((f) => [f.slug, f]));
const hoursFile = JSON.parse(readFileSync('firms_hours.json', 'utf8'));
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
let stale = 0;
const write = (file, text) => { if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { if (CHECK) stale++; else writeFileSync(file, text); } };

// 1. batch firms
for (const file of readdirSync('data').filter((f) => /^firms-batch-\d+\.json$/.test(f))) {
  const batch = JSON.parse(readFileSync(`data/${file}`, 'utf8'));
  for (const f of batch) if (found[f.slug]) f.hours = found[f.slug].hours;
  write(`data/${file}`, JSON.stringify(batch, null, 1) + '\n');
}

// 2. original firms
const sql = ['-- Generated by scripts/apply-found-hours.mjs from data/hours-found.json. Do not edit by hand.'];
for (const slug of Object.keys(found).sort()) {
  const f = firms[slug];
  if (!f) continue; // a batch firm
  const hours = found[slug].hours;
  if (!hoursFile[slug]) hoursFile[slug] = hours;
  sql.push(`UPDATE firms SET hours = ${q(JSON.stringify(hours))}, updated_at = datetime('now') WHERE slug = ${q(slug)} AND hours IS NULL;`);
  const page = `firms/${slug}.html`;
  if (!existsSync(page)) continue;
  const html = readFileSync(page, 'utf8');
  if (html.includes('class="hours-card"')) continue;
  const at = html.indexOf('<div class="guide">');
  if (at < 0) { console.error('no place for hours in', slug); continue; }
  const card = hoursCard(hours, f.province).replace('Hours as provided by the firm.', 'Hours as listed on the firm&rsquo;s website.');
  if (CHECK) stale++; else writeFileSync(page, html.slice(0, at) + card + '\n    ' + html.slice(at));
}
// Same style as the existing file (single line, ", " and ": " separators), so the diff shows only the new firms.
write('firms_hours.json', JSON.stringify(hoursFile).replace(/":/g, '": ').replace(/,(?=["\[])/g, ', '));
write('db/hours-updates.sql', sql.join('\n') + '\n');
if (CHECK && stale) { console.error('found hours are not applied: run node scripts/apply-found-hours.mjs'); process.exit(1); }
console.log(CHECK ? 'found hours applied' : `hours applied to ${Object.keys(found).length} firms`);
