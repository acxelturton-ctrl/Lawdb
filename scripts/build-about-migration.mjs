// One-time data migration for databases that ALREADY contain the firms (production): copy each firm's
// written description from its hand-built page into firms.about.
//   node scripts/build-about-migration.mjs   -> writes migrations/0004_import_about.sql
// Idempotent in SQL (only fills rows where about IS NULL). Fresh databases get the same text from the seed
// script instead (the seed runs after migrations), see scripts/build-seed.mjs.
import { readFileSync, writeFileSync } from 'node:fs';
import { aboutFromPage } from './lib/about.mjs';

const root = new URL('../', import.meta.url);
const firms = JSON.parse(readFileSync(new URL('firms_data.json', root), 'utf8'));
const sql = (s) => `'${s.replace(/'/g, "''")}'`;
const lines = ['-- GENERATED by scripts/build-about-migration.mjs from the existing firm pages. Do not edit by hand.'];
let n = 0;
for (const f of firms) {
  const text = aboutFromPage(f.slug);
  if (!text) continue;
  lines.push(`UPDATE firms SET about = ${sql(text)} WHERE slug = ${sql(f.slug)} AND about IS NULL;`);
  n++;
}
writeFileSync(new URL('migrations/0004_import_about.sql', root), lines.join('\n') + '\n');
console.log(`about text for ${n} of ${firms.length} firms`);
