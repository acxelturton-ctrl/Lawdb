// The list of city pages that exist (/<province>/<city>/), so the breadcrumb on a firm's page links only to pages that are there.
// Writes src/render/city-hubs.generated.js.
//   node scripts/build-city-hubs.mjs           rewrite the file
//   node scripts/build-city-hubs.mjs --check   fail if the committed file is out of date
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

const CHECK = process.argv.includes('--check');
const PROVINCES = ['alberta', 'british-columbia', 'manitoba', 'ontario', 'quebec'];

const hubs = [];
for (const p of PROVINCES) {
  for (const d of readdirSync(p, { withFileTypes: true })) {
    if (d.isDirectory() && existsSync(`${p}/${d.name}/index.html`)) hubs.push(`${p}/${d.name}`);
  }
}
hubs.sort();

const out = `// Generated by scripts/build-city-hubs.mjs (npm run check fails when it is out of date). The city pages that exist, as province/city.
export const CITY_HUBS = new Set(${JSON.stringify(hubs)});
`;

const file = 'src/render/city-hubs.generated.js';
if (CHECK) {
  const have = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (have !== out) { console.error(`${file} is out of date: run node scripts/build-city-hubs.mjs`); process.exit(1); }
  console.log(`city page list ok: ${hubs.length} cities`);
} else {
  writeFileSync(file, out);
  console.log(`wrote ${file} (${hubs.length} cities)`);
}
