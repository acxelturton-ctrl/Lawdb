// Builds db/extra-firms.sql from the released data/firms-batch-*.json files (see data/release.json): firms added in batches after the original 370.
// These rows are live, profile pages are built from the database (page_mode 'dynamic'), and INSERT OR IGNORE means
// re-running never overwrites edits made in the admin area or by an owner.
// Kept apart from db/seed.sql on purpose: the tests compare the seed to the static pages, which have no copy of these firms.
//   node scripts/build-extra-firms.mjs          writes db/extra-firms.sql
//   node scripts/build-extra-firms.mjs --check  fails if the file is out of date or a record is malformed
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { normalizeHours } from '../src/lib/firm-edit.js';

const root = new URL('../', import.meta.url);
const CASES = ['traffic', 'criminal', 'family', 'injury', 'realestate', 'wills', 'business', 'employment', 'immigration', 'litigation'];
const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

// data/release.json lists the batch numbers that are live. Batches not listed stay in the repository and are not loaded into the
// database, so firms can be released a hundred or so at a time (a few hundred new pages at once can look like a spike to Google).
const released = new Set(JSON.parse(readFileSync(new URL('data/release.json', root), 'utf8')).released);
const files = readdirSync(new URL('data/', root)).filter((f) => /^firms-batch-\d+\.json$/.test(f) && released.has(Number(f.match(/\d+/)[0]))).sort();
const seen = new Set();
const out = ['-- Generated by scripts/build-extra-firms.mjs from data/firms-batch-*.json. Do not edit by hand.'];
for (const file of files) {
  for (const rec of JSON.parse(readFileSync(new URL(`data/${file}`, root), 'utf8'))) {
    const { about, hours, ...f } = rec;
    const bad = (why) => { throw new Error(`${file}: ${rec.name || '?'}: ${why}`); };
    if (!/^[a-z0-9-]{3,90}$/.test(f.slug)) bad('slug');
    if (seen.has(f.slug)) bad('duplicate slug');
    seen.add(f.slug);
    if (!f.name || !f.city || !['ON', 'QC', 'BC', 'AB', 'MB'].includes(f.province)) bad('name, city or province');
    if (!(f.lat >= 41 && f.lat <= 84 && f.lng >= -142 && f.lng <= -52)) bad('coordinates');
    if (!(f.rating >= 0 && f.rating <= 5) || !Number.isInteger(f.count)) bad('rating or count');
    if (!/^\+1\d{10}$/.test(f.phone)) bad('phone');
    if (!/^https?:\/\/[^\s/]+$/.test(f.website)) bad('website');
    if (!f.caseTypes.every((c) => CASES.includes(c))) bad('caseTypes');
    if (!about || about.length > 2000) bad('about');
    out.push(
      'INSERT OR IGNORE INTO firms (slug,name,city,province,region,featured,rating,review_count,lat,lng,data,hours,about,page_mode,status,created_by) VALUES (' +
        [q(f.slug), q(f.name), q(f.city), q(f.province), q(f.region || ''), 0, q(f.rating), q(f.count), q(f.lat), q(f.lng), q(JSON.stringify(f)), hours ? q(JSON.stringify(normalizeHours(hours))) : 'NULL', q(about), "'dynamic'", "'live'", 'NULL'].join(',') +
        ');'
    );
  }
}
const sql = out.join('\n') + '\n';
const target = new URL('db/extra-firms.sql', root);
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== sql) { console.error('db/extra-firms.sql is out of date: run node scripts/build-extra-firms.mjs'); process.exit(1); }
  console.log(`extra-firms.sql up to date: ${seen.size} firms`);
} else {
  mkdirSync(new URL('db/', root), { recursive: true });
  writeFileSync(target, sql);
  console.log(`extra-firms.sql: ${seen.size} firms from ${files.length} file(s)`);
}
