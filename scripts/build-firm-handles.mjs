// Every firm's public address handle (lawdb.ca/firm/<handle>) and the SQL that gives it to the database.
//   node scripts/build-firm-handles.mjs                      adds a handle for every firm that has none (the others never change) and writes db/handles-updates.sql
//   node scripts/build-firm-handles.mjs --check              fails if a firm has no handle, two firms share one, or db/handles-updates.sql is out of date (npm run check runs this)
//   node scripts/build-firm-handles.mjs --from <file.json>   the list of firms to give handles to, instead of the site's own list (the first run used the live list, which also has
//                                                            the firms that listed themselves in the database only)
// db/handles-updates.sql is applied with the other updates on every deploy; each statement only fills a handle that is empty, so it is safe to run twice.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { loadSiteFirms } from './lib/site-firms.mjs';
import { loadHandles, assignHandles, HANDLES_FILE, HANDLE_RE, RENAMES_FILE } from './lib/firm-handles.mjs';

const CHECK = process.argv.includes('--check');
const fromIdx = process.argv.indexOf('--from');
const firms = (fromIdx > 0 ? JSON.parse(readFileSync(process.argv[fromIdx + 1], 'utf8')) : loadSiteFirms()).map((f) => ({ slug: f.slug, city: f.city, count: f.count ?? f.review_count }));
const existing = loadHandles();
// A firm renamed in the live database (data/firm-renames.json, old slug -> new slug): the old slug is no longer a listing there, so it takes no handle of its own; pages built from the
// repository's record of the firm link to the address the firm has now.
const renames = existsSync(RENAMES_FILE) ? JSON.parse(readFileSync(RENAMES_FILE, 'utf8')) : {};
const fresh = assignHandles(firms.filter((f) => !renames[f.slug]), existing);
const all = { ...existing, ...fresh };
for (const [oldSlug, newSlug] of Object.entries(renames)) { delete all[oldSlug]; if (all[newSlug]) all[oldSlug] = all[newSlug]; } // an alias: the old slug has the new slug's handle
const sorted = Object.fromEntries(Object.entries(all).sort(([a], [b]) => a.localeCompare(b)));

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sql = '-- Generated by scripts/build-firm-handles.mjs from data/firm-handles.json. Do not edit by hand.\n' +
  Object.entries(sorted).filter(([slug]) => !renames[slug]).map(([slug, h]) => `UPDATE firms SET handle = ${q(h)}, data = json_set(data, '$.handle', ${q(h)}) WHERE slug = ${q(slug)} AND handle IS NULL;`).join('\n') + '\n';

const values = Object.entries(sorted).filter(([slug]) => !renames[slug]).map(([, h]) => h); // an alias shares its new slug's handle
const problems = [];
if (new Set(values).size !== values.length) problems.push('two firms share a handle');
for (const [slug, h] of Object.entries(sorted)) if (!HANDLE_RE.test(h) || h.length < 3 || h.length > 80) problems.push(`bad handle for ${slug}: ${h}`);

if (CHECK) {
  const missing = Object.keys(fresh);
  if (missing.length) problems.push(`${missing.length} firm(s) have no handle yet, e.g. ${missing[0]} (run node scripts/build-firm-handles.mjs)`);
  let current = ''; try { current = readFileSync(new URL('../db/handles-updates.sql', import.meta.url), 'utf8'); } catch { /* missing */ }
  if (current !== sql) problems.push('db/handles-updates.sql is out of date (run node scripts/build-firm-handles.mjs)');
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  console.log(`firm handles: ${values.length} firms, every handle is unique`);
} else {
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  writeFileSync(HANDLES_FILE, JSON.stringify(sorted, null, 1) + '\n');
  writeFileSync(new URL('../db/handles-updates.sql', import.meta.url), sql);
  console.log(`firm handles: ${Object.keys(fresh).length} added, ${values.length} in all`);
}
