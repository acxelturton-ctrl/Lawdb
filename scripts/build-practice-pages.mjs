// Lists the province practice pages that exist (ontario/family-lawyers.html ...), so a firm's profile only links to pages that are there.
//   node scripts/build-practice-pages.mjs          writes src/lib/practice-pages.generated.js
//   node scripts/build-practice-pages.mjs --check  fails when it is out of date
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';

const DIRS = ['ontario', 'quebec', 'british-columbia', 'alberta', 'manitoba'];
const SLUGS = ['business-lawyers', 'criminal-defence-lawyers', 'traffic-ticket-lawyers', 'personal-injury-lawyers', 'employment-lawyers', 'family-lawyers', 'litigation-lawyers', 'wills-estate-lawyers', 'immigration-lawyers', 'real-estate-lawyers'];
const pages = [];
for (const d of DIRS) if (existsSync(d)) for (const f of readdirSync(d)) { const s = f.replace(/\.html$/, ''); if (f.endsWith('.html') && SLUGS.includes(s)) pages.push(`${d}/${s}`); }
pages.sort();
const out = `// Generated by scripts/build-practice-pages.mjs. Do not edit by hand.\nexport const PRACTICE_PAGES = ${JSON.stringify(pages)};\n`;
const target = 'src/lib/practice-pages.generated.js';
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) { console.error('practice pages list is out of date: run node scripts/build-practice-pages.mjs'); process.exit(1); }
  console.log(`practice pages list is up to date: ${pages.length} pages`);
} else { writeFileSync(target, out); console.log(`${pages.length} practice pages`); }
