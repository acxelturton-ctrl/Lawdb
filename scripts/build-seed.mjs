// Builds db/seed.sql from firms_data.json, firms_hours.json and blog_data.json.
// Re-runnable: it upserts, so it is safe to seed again after editing the JSON.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const read = (f) => JSON.parse(readFileSync(new URL(`../${f}`, import.meta.url), 'utf8'));
const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => q(JSON.stringify(v));

const firms = read('firms_data.json');
const hours = read('firms_hours.json');
const posts = read('blog_data.json');

const out = ['-- Generated by scripts/build-seed.mjs. Do not edit by hand.'];

for (const f of firms) {
  out.push(
    `INSERT INTO firms (slug,name,city,province,region,featured,rating,review_count,lat,lng,data,hours) VALUES (` +
      [q(f.slug), q(f.name), q(f.city), q(f.province), q(f.region), f.featured ? 1 : 0, q(f.rating), q(f.count), q(f.lat), q(f.lng), json(f), hours[f.slug] ? json(hours[f.slug]) : 'NULL'].join(',') +
      `) ON CONFLICT(slug) DO UPDATE SET name=excluded.name,city=excluded.city,province=excluded.province,region=excluded.region,featured=excluded.featured,rating=excluded.rating,review_count=excluded.review_count,lat=excluded.lat,lng=excluded.lng,data=excluded.data,hours=excluded.hours,updated_at=datetime('now');`
  );
}
posts.forEach((p, i) => {
  out.push(
    `INSERT INTO blog_posts (slug,title,city,province,sort_order,data) VALUES (` +
      [q(p.slug), q(p.title), q(p.city), q(p.province), i, json(p)].join(',') +
      `) ON CONFLICT(slug) DO UPDATE SET title=excluded.title,city=excluded.city,province=excluded.province,sort_order=excluded.sort_order,data=excluded.data,updated_at=datetime('now');`
  );
});

mkdirSync(new URL('../db/', import.meta.url), { recursive: true });
writeFileSync(new URL('../db/seed.sql', import.meta.url), out.join('\n') + '\n');
console.log(`seed.sql: ${firms.length} firms, ${posts.length} blog posts`);
